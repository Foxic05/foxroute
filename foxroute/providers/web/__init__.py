"""Веб-сессии — то, ради чего всё затевалось.

Это чат-сервисы, к которым ходят по кукам обычного залогиненного аккаунта.
Официального интерфейса у них нет: протоколы сняты с живого трафика, а часть
пришлось расковырять (подпись запроса у Poe, самодельный protobuf у Meta AI,
капча у Z.ai).

Отсюда следуют свойства, которых нет у обычного API и которые определяют
всю обвязку слоя:

* **Хрупкость.** Сервис волен поменять формат в любой день, никого не
  предупредив. Поэтому каждый адаптер сверяется с живым сервисом
  (``bench/smoke.py``), а не покрывается моками.
* **Квота в сообщениях, а не в токенах.** И у большинства она не видна:
  из двадцати сервисов остаток отдают семеро. Для остальных схема
  реактивная — поймали отказ, поставили паузу, ушли к другому.
* **Один разговор за раз.** Веб-сессия — это одна вкладка браузера:
  параллельные запросы в неё не ускоряют работу, а встают в очередь внутри
  сервиса. Отсюда ``Provider.slots = 1``.
* **Условия использования.** Автоматический доступ их нарушает. Это
  инструмент для своих аккаунтов, а не основа сервиса для других людей.

Официальные API живут рядом, в ``foxroute.providers.api``: у них другие
свойства и мешать их с этими не стоит.
"""
