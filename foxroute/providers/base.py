"""Контракт провайдера.

Один интерфейс на всех: под ним и обычный HTTPS с SSE, и бинарный WebSocket
с самодельным protobuf, и Socket.IO облачного агента. Вызывающий про это
не знает и знать не должен.

Три решения, определяющие этот слой:

1. **Основной примитив — поток кусков, а не готовая строка.** Все эти сервисы
   стримят под капотом; собирать всё в строку внутри адаптера значило терять
   ``stream=true`` наверху. Здесь наоборот: неблокирующий поток базовый,
   а целый ответ — тривиальная склейка.

2. **Куски нормализованы до приращений.** Сервисы шлют по-разному: Kimi и
   Mistral присылают НАКОПЛЕННЫЙ текст (``op: set`` заменяет, ``append``
   дописывает), Meta AI — растущее поле ``f2``. Приводить это к дельтам —
   обязанность адаптера, иначе каждый потребитель будет вычитать префиксы
   заново и однажды ошибётся.

3. **Адаптер делает только протокол.** Ни статистики, ни суточных лимитов,
   ни логов, ни подсказок к промпту — всё это забота слоя выше. Смешать их
   с адаптером значит лишить провайдера возможности протестировать и
   переиспользовать его отдельно.
"""
from __future__ import annotations

import abc
from dataclasses import dataclass, field, replace
from typing import Callable, Iterator

from foxroute.errors import Unsupported


# ── Возможности ───────────────────────────────────────────────────────

@dataclass(frozen=True)
class Capabilities:
    """Что провайдер умеет сверх обычного текста.

    Список будет расти: часть сервисов принимает файлы и картинки, часть
    ищет в сети. Пока эти возможности не изучены поштучно, все флаги, кроме
    текста, выключены — заявленное, но непроверенное умение хуже отсутствия,
    потому что маршрутизатор пошлёт туда запрос и получит отказ.

    Включать флаг можно только после сверки с живым сервисом.
    """

    text: bool = True
    #: Отдаёт ответ по мере готовности.
    #:
    #: Ложно у тех, чей эндпоинт возвращает готовый текст целиком: DeepAI
    #: отвечает обычным POST, Gemini Web ходит через библиотеку без потока.
    #: Контракт это допускает — он требует, чтобы склейка кусков давала
    #: полный ответ, а не чтобы кусков было много. Флаг нужен, чтобы
    #: отсутствие потока не выглядело поломкой при сверке, и чтобы наверху
    #: можно было честно ответить на ``stream=true``.
    streaming: bool = True
    #: Рисует картинки по описанию.
    images_out: bool = False
    #: Принимает картинки на вход и понимает их.
    vision: bool = False
    #: Принимает файлы вложением.
    files_in: bool = False
    #: Сам собирает файлы и отдаёт их — таблицу, архив, картинку из кода.
    #:
    #: Отдельно от ``files_in``: принимать и создавать умеют разные сервисы,
    #: и делают это разными путями. У ChatGPT созданное лежит в песочнице
    #: кода и в тексте помечено несуществующей ссылкой ``sandbox:/…``;
    #: файлом это станет только после отдельного запроса.
    files_out: bool = False
    #: Отвечает с опорой на живую выдачу, а не только на память модели.
    #: Важно для ссылок: модель без доступа в сеть выдумывает правдоподобные
    #: URL, и отличить их от настоящих по виду нельзя.
    web_search: bool = False
    #: Помнит беседу на своей стороне, её можно продолжать.
    conversations: bool = False
    #: Поддерживает РЕЖИМ РАЗМЫШЛЕНИЯ.
    #:
    #: Критерий — по кнопке/режиму в интерфейсе САМОГО сервиса, а не по
    #: тому, приходит ли отдельный поток мыслей. Часть провайдеров (Copilot,
    #: Alice, ChatGPT, Gemini Web) режим включает, но ход мысли отдельно не
    #: выделяет — они оставляют базовый ``stream_rich`` (всё как ``text``).
    #: Кто отдаёт мысли отдельным потоком (Qwen, DeepSeek, claude_web),
    #: переопределяет ``stream_rich`` и метит их типом ``thinking``.
    #: Kimi флаг принимает и молча игнорирует — ему thinking НЕ ставим.
    thinking: bool = False
    #: Умеет ГЛУБОКОЕ ИССЛЕДОВАНИЕ: сам ищет по многим источникам и сводит
    #: их в развёрнутый ответ со ссылками.
    #:
    #: Отдельно от ``web_search``: обычный поиск — это одна выдача под
    #: вопрос, а исследование — несколько запросов подряд и сводка. Стоит
    #: оно дороже (время и квота), поэтому включается только по просьбе.
    deep_research: bool = False


@dataclass
class Attachment:
    """Вложение к запросу.

    ``data`` или ``url`` — что-то одно. Провайдеры принимают по-разному:
    кто-то грузит байты, кто-то ждёт ссылку, поэтому приведение — забота
    адаптера, а не вызывающего.
    """

    kind: str = "file"          # "file" | "image"
    data: bytes | None = None
    url: str = ""
    filename: str = ""
    mime: str = ""


# ── Запрос и беседа ───────────────────────────────────────────────────

@dataclass
class Request:
    """Что просим у провайдера.

    Промпт уже собран: схлопывание ``messages[]`` и рендер инструментов —
    забота translate.py. Адаптер получает готовый текст и не знает ни про
    роли, ни про инструменты.
    """

    prompt: str
    #: Имя модели у провайдера. None — взять из реестра по умолчанию.
    model: str | None = None
    #: Потолок ожидания целиком, секунды. Grok на коротком вопросе тратит
    #: 18-26 секунд, Manus поднимает виртуальный компьютер на 14-40 —
    #: значение по умолчанию щедрое намеренно.
    timeout: float = 300.0
    #: Продолжить серверную беседу вместо создания новой.
    conversation: "Conversation | None" = None
    #: Вложения. Провайдер без нужной возможности обязан отказать явно.
    attachments: list[Attachment] = field(default_factory=list)
    #: Просить ответ с опорой на живую выдачу.
    web_search: bool = False
    #: Включить режим размышлений (deep thinking / reasoning).
    #: Не все провайдеры умеют; если не умеет — игнорирует.
    thinking: bool = False
    #: Просить глубокое исследование вместо обычного ответа.
    deep_research: bool = False
    #: Инструменты в формате OpenAI. Провайдеру они НЕ передаются: у
    #: веб-сессий нет протокола функций. Сервер описывает их построчно в
    #: промпте, а по этому полю потом вылавливает вызов из ответа.
    tools: list = field(default_factory=list)
    #: Соотношение сторон для рисования: «1:1», «3:2», «2:3».
    #: Пиксельный размер сервисы не принимают, только пропорцию.
    aspect: str = "1:1"
    #: Потолок длины ответа. None — не ограничивать.
    #:
    #: Умолчания тут нет намеренно: фиксированный потолок в слое общего
    #: назначения означал бы молчаливую обрезку длинного ответа. Веб-сессии
    #: такой ручки не имеют вовсе и значение игнорируют.
    max_tokens: int | None = None
    #: Температура. None — оставить умолчание сервиса. Веб-сессии не умеют.
    temperature: float | None = None


@dataclass
class Conversation:
    """Ручка на беседу, живущую на стороне сервиса.

    Нужна для продолжения контекста без пересылки всей истории: у ChatGPT,
    DeepSeek и прочих чат живёт на сервере и помнит предыдущие ходы. Поля
    намеренно непрозрачные — их формат знает только конкретный адаптер
    (ChatGPT, например, обязан вести цепочку ``parent_message_id``).

    Хранить эту ручку долго нельзя без оглядки: состояние чужое, и вместе
    с протухшей кукой теряется вся беседа.
    """

    provider: str
    chat_id: str
    #: Идентификатор последнего сообщения — для сервисов, где ходы
    #: связываются в цепочку, а не просто лежат в одном чате.
    last_message_id: str = ""
    extra: dict = field(default_factory=dict)


# ── Доступ ────────────────────────────────────────────────────────────

@dataclass(frozen=True)
class Credential:
    """Доступ к одному аккаунту провайдера.

    ``value`` — строка из хранилища (кука, JWT, API-ключ). Пусто у тех, кто
    авторизуется файлами (Meta AI, MS Copilot) или не требует ничего (Z.ai).

    ``account`` — метка аккаунта внутри провайдера. Пул из нескольких
    аккаунтов на один сервис — штатный режим: это прямой способ поднять
    квоту, и адаптер обязан быть к нему готов.
    """

    provider: str
    value: str = ""
    account: str = "default"

    def __post_init__(self) -> None:
        # Обрезаем пробелы и переводы строк по краям — единственное, что
        # правим молча. Это следы копирования из DevTools, и они ломают
        # заголовок гарантированно.
        #
        # Всё остальное пропускаем как есть: отвергать ключ по своим догадкам
        # о его форме нельзя. Сервис может однажды начать выдавать что угодно,
        # и наша проверка окажется единственным, что мешает работать. Если
        # значение действительно не пролезет в заголовок, это выяснится при
        # запросе — и _http переведёт сбой в понятную ошибку.
        object.__setattr__(self, "value", (self.value or "").strip())

    @classmethod
    def expand(cls, provider: str, raw: str) -> list["Credential"]:
        """Развернуть строку из хранилища в пул учёток.

        Разделитель ``|`` значит РАЗНОЕ у разных провайдеров, и путать эти
        два смысла нельзя (см. ``registry.MULTI_KEY``):

        * у AgentRouter это несколько независимых ключей — каждый со своим
          кошельком и своей квотой, то есть настоящий пул;
        * у всех остальных наоборот, склейка частей ОДНОГО доступа: у
          ChatGPT браузер режет длинную куку надвое, у Gemini Web это две
          разные куки, у Grok — ``sso`` и ``sso-rw``.

        Ошибиться тут дорого и незаметно: пул, принятый за один ключ,
        уезжает в заголовок целиком и даёт 401, который выглядит как
        протухший доступ.
        """
        from foxroute.registry import splits_pool

        raw = (raw or "").strip()
        if splits_pool(provider) and "|" in raw:
            parts = [p.strip() for p in raw.split("|") if p.strip()]
            return [cls(provider, part, account=str(number))
                    for number, part in enumerate(parts, 1)]
        return [cls(provider, raw)]

    @property
    def header_safe(self) -> bool:
        """Пролезет ли значение в заголовок HTTP (туда можно только latin-1)."""
        try:
            self.value.encode("latin-1")
        except UnicodeEncodeError:
            return False
        return True

    def __repr__(self) -> str:
        # Секрет не должен попасть ни в лог, ни в трейсбек.
        shown = f"{len(self.value)} симв" if self.value else "без ключа"
        return f"Credential({self.provider}/{self.account}, {shown})"


# ── Провайдер ─────────────────────────────────────────────────────────

class Provider(abc.ABC):
    """Базовый адаптер.

    Наследник реализует ``_stream`` (текст) и/или ``_draw`` (картинки) —
    ровно то, что заявлено в ``capabilities``. Публичные ``stream`` и
    ``draw`` — обёртки: они сверяют запрос с возможностями ДО обращения к
    сети, чтобы отказ приходил сразу, а не после того, как запрос уже съел
    сообщение из квоты.
    """

    #: Ключ реестра (`qwen`, `chatgpt`, …).
    name: str = ""
    #: Работает ли адаптер ОТ ИМЕНИ АККАУНТА.
    #:
    #: Часть сервисов отвечает и анонимному гостю (Alice, Perplexity, DeepAI,
    #: Pi, Copilot без токена). Это рабочий режим, но урезанный: лимиты ниже,
    #: памяти чатов нет, а у некоторых доступны не все модели. Ради лимитов
    #: аккаунты и нужны, поэтому анонимный режим — запасной путь, а не
    #: равноправный: включается он явно, через ``allow_anonymous`` в ``build``.
    #:
    #: Адаптер, умеющий оба режима, выставляет это поле в конструкторе.
    authorized: bool = True
    #: Что умеет. Наследник переопределяет только то, что подтверждено сверкой.
    capabilities: Capabilities = Capabilities()
    #: Сколько запросов провайдер тянет одновременно. У веб-сессии это ОДИН
    #: разговор в браузере: параллельные запросы в него не ускоряют работу,
    #: а встают в очередь внутри сервиса.
    slots: int = 1

    def __init__(self, credential: Credential, model: str = "",
                 on_rotate: "Callable[[Credential], None] | None" = None):
        self.credential = credential
        self.model = model
        #: Куда сообщить, что доступ обновился сам собой.
        self.on_rotate = on_rotate

    # ── обязательное ──────────────────────────────────────────────────

    def _stream(self, req: Request) -> Iterator[str]:
        """Выдавать ПРИРАЩЕНИЯ текста по мере готовности.

        Контракт, обязательный к соблюдению:

        * куски — только новое, склейка всех кусков даёт полный ответ;
        * служебные потоки в выдачу не попадают: рассуждения модели
          (``phase: think`` у Qwen, секции ``reasoning-*`` у Meta AI,
          события ``progress`` у Pi) — это не ответ;
        * отказ поднимается исключением из foxroute.errors, а не возвращается
          строкой.

        Не обязателен: провайдер может только рисовать (Bing Images). Тогда
        он оставляет этот метод как есть, а ``capabilities.text`` ложно.
        """
        raise Unsupported(f"{self.name}: текста не пишет", self.name)

    def _draw(self, req: Request) -> list[str]:
        """Нарисовать картинки, вернуть ссылки на них.

        Ссылки, а не байты: сервисы отдают именно адреса, и скачивание —
        забота вызывающего. Тащить мегабайты через слой, которому они не
        нужны, незачем.
        """
        raise Unsupported(f"{self.name}: рисовать не умеет", self.name)

    # ── публичное ─────────────────────────────────────────────────────

    def stream(self, req: Request) -> Iterator[str]:
        """Поток приращений с проверкой возможностей."""
        self.validate(req)
        if not self.capabilities.text:
            raise Unsupported(
                f"{self.name}: текста не пишет, только рисует", self.name)
        return self._stream(req)

    def stream_rich(self, req: Request) -> Iterator[tuple[str, str]]:
        """Поток пар (тип, текст) — для провайдеров с режимом размышлений.

        Типы: ``"text"`` — ответ, ``"thinking"`` — размышление.
        По умолчанию оборачивает обычный ``_stream`` в пары ``("text", кусок)``.
        Адаптер с thinking переопределяет этот метод.
        """
        self.validate(req)
        if not self.capabilities.text:
            raise Unsupported(
                f"{self.name}: текста не пишет, только рисует", self.name)
        for piece in self._stream(req):
            yield ("text", piece)

    def complete(self, req: Request) -> str:
        """Целый ответ одной строкой."""
        return "".join(self.stream(req)).strip()

    def draw(self, req: Request) -> list[str]:
        """Нарисовать картинки. Возвращает ссылки."""
        self.validate(req)
        if not self.capabilities.images_out:
            raise Unsupported(f"{self.name}: рисовать не умеет", self.name)
        return self._draw(req)

    def start_conversation(self, req: Request) -> Conversation:
        """Начать серверную беседу, которую потом можно продолжать."""
        raise Unsupported(
            f"{self.name}: продолжение беседы не реализовано", self.name)

    def close(self) -> None:
        """Освободить ресурсы. По умолчанию нечего."""

    # ── служебное ─────────────────────────────────────────────────────

    def validate(self, req: Request) -> None:
        """Отказать заранее, если запрошено неподдержанное.

        Отказ до обращения к сети, а не после: запрос к веб-сессии стоит
        сообщения из квоты, и сжигать его на заведомо невыполнимом незачем.
        """
        caps = self.capabilities
        if req.conversation is not None and not caps.conversations:
            raise Unsupported(
                f"{self.name}: продолжение беседы не поддерживается", self.name)
        if req.web_search and not caps.web_search:
            raise Unsupported(
                f"{self.name}: поиск в сети не поддерживается", self.name)
        if req.deep_research and not caps.deep_research:
            raise Unsupported(
                f"{self.name}: глубокое исследование не поддерживается",
                self.name)
        for item in req.attachments:
            if item.kind == "image" and not caps.vision:
                raise Unsupported(
                    f"{self.name}: картинки на вход не принимает", self.name)
            if item.kind != "image" and not caps.files_in:
                raise Unsupported(
                    f"{self.name}: файлы на вход не принимает", self.name)

    def rotated(self, new_value: str) -> None:
        """Сообщить, что сервис выдал новый доступ взамен старого.

        Так делают Kimi и MS Copilot: в ответ на обновление они возвращают
        свежий refresh-токен, а прежний рано или поздно перестают принимать.

        Адаптер только СООБЩАЕТ о ротации, а решает хранилище — и это не
        придирка. У Kimi исходный токен из куки продолжает приниматься
        после ротации, а выдаются каждый раз новые и разные.
        Значит в куке лежит долгоживущий корневой токен, а сервис отдаёт
        временные; перезаписать хранилище временным — променять месяцы жизни
        доступа на часы. Разумная политика — держаться исходного, пока его
        принимают, и повышать полученный только когда прежний отвергнут.

        Без обратной связи обновлённый токен осел бы в поле экземпляра и
        умер вместе с процессом. Для Kimi это безвредно, но у MS Copilot
        доступ устроен иначе, и там такая потеря значит перелогин.

        Хранилище подписывается через ``on_rotate``. Писать на диск оно обязано
        под блокировкой: у одного доступа не должно быть двух писателей.
        """
        if not new_value or new_value == self.credential.value:
            return
        self.credential = replace(self.credential, value=new_value)
        if self.on_rotate is not None:
            self.on_rotate(self.credential)

    def resolve_model(self, req: Request) -> str:
        from foxroute.registry import config

        return req.model or self.model or config(self.name).get("model", "")

    def __repr__(self) -> str:
        return f"<{type(self).__name__} {self.name}/{self.credential.account}>"
